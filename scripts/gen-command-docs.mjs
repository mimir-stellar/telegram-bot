#!/usr/bin/env node
/**
 * scripts/gen-command-docs.mjs
 *
 * Generates docs/commands.md from the canonical command definitions in dist/.
 *
 * Usage:
 *   node scripts/gen-command-docs.mjs            # Generate / update docs/commands.md
 *   node scripts/gen-command-docs.mjs --check    # Exit non-zero if docs/commands.md is stale or missing
 *   node scripts/gen-command-docs.mjs --help     # Print usage information
 */

import { existsSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

import { COMMANDS } from "../dist/bot.js";
import { COMMAND_DESCRIPTIONS } from "../dist/i18n.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "..");
export const DEFAULT_DOCS_PATH = path.join(repoRoot, "docs", "commands.md");

/**
 * Known allowlist-gated commands in src/bot.ts.
 * Fallback in case COMMANDS items do not explicitly declare allowlistGated.
 */
const KNOWN_ALLOWLIST_GATED = new Set(["status", "contracts", "health", "preview"]);

/**
 * Returns whether a command is gated by ALLOWED_CHAT_IDS.
 */
export function isAllowlistGated(cmd) {
  if (typeof cmd.allowlistGated === "boolean") {
    return cmd.allowlistGated;
  }
  return KNOWN_ALLOWLIST_GATED.has(cmd.command);
}

/**
 * Returns whether a command is restricted to the operator.
 */
export function isOperatorOnly(cmd) {
  return Boolean(cmd.operatorOnly);
}

/**
 * Generates the deterministic Markdown documentation string for commands.
 *
 * @param {Array<{ command: string, description?: string, operatorOnly?: boolean, allowlistGated?: boolean }>} [commands]
 * @returns {string} Deterministic Markdown documentation
 */
export function formatCommandDocs(commands = COMMANDS) {
  const lines = [
    "# Telegram Bot Commands",
    "",
    "<!-- This file is auto-generated by scripts/gen-command-docs.mjs. Do not edit manually. -->",
    "",
    "| Command | Description | Operator-only | Allowlist-gated |",
    "|---|---|---|---|",
  ];

  for (const item of commands) {
    const cmdName = item.command.startsWith("/") ? item.command : `/${item.command}`;
    const desc = item.description || COMMAND_DESCRIPTIONS[item.command] || "";
    const operatorOnly = isOperatorOnly(item) ? "Yes" : "No";
    const allowlistGated = isAllowlistGated(item) ? "Yes" : "No";

    lines.push(`| \`${cmdName}\` | ${desc} | ${operatorOnly} | ${allowlistGated} |`);
  }

  lines.push(
    "",
    "## Access Controls",
    "",
    "- **Operator-only**: Requires `OPERATOR_TELEGRAM_USER_ID` to be configured. Only the designated operator can execute these commands.",
    "- **Allowlist-gated**: Restricted to chats listed in `ALLOWED_CHAT_IDS`. If `ALLOWED_CHAT_IDS` is unset or empty, these commands are open to any chat.",
    "",
  );

  return lines.join("\n");
}

/**
 * Writes the generated docs to the specified path.
 *
 * @param {string} [targetPath=DEFAULT_DOCS_PATH]
 * @param {Array} [commands=COMMANDS]
 */
export function writeCommandDocs(targetPath = DEFAULT_DOCS_PATH, commands = COMMANDS) {
  const content = formatCommandDocs(commands);
  const dir = path.dirname(targetPath);
  if (!existsSync(dir)) {
    mkdirSync(dir, { recursive: true });
  }
  writeFileSync(targetPath, content, "utf8");
}

/**
 * Checks whether the file at targetPath matches the expected generated docs.
 *
 * @param {string} [targetPath=DEFAULT_DOCS_PATH]
 * @param {Array} [commands=COMMANDS]
 * @returns {{ ok: boolean, reason?: string }}
 */
export function checkCommandDocs(targetPath = DEFAULT_DOCS_PATH, commands = COMMANDS) {
  if (!existsSync(targetPath)) {
    return { ok: false, reason: `File not found: ${targetPath}` };
  }

  const actual = readFileSync(targetPath, "utf8").replace(/\r\n/g, "\n");
  const expected = formatCommandDocs(commands);

  if (actual !== expected) {
    return {
      ok: false,
      reason: `Documentation at ${targetPath} is stale. Run "node scripts/gen-command-docs.mjs" to update.`,
    };
  }

  return { ok: true };
}

/**
 * Parses CLI arguments and executes either generate or check mode.
 */
export function main(argv = process.argv.slice(2)) {
  let checkMode = false;
  let targetPath = DEFAULT_DOCS_PATH;

  for (const arg of argv) {
    if (arg === "--check") {
      checkMode = true;
    } else if (arg.startsWith("--output=")) {
      targetPath = path.resolve(arg.slice("--output=".length));
    } else if (arg.startsWith("--path=")) {
      targetPath = path.resolve(arg.slice("--path=".length));
    } else if (arg === "--help" || arg === "-h") {
      console.log(`Usage: node scripts/gen-command-docs.mjs [--check] [--output=PATH]

Options:
  --check        Verify that docs/commands.md is up to date (exit non-zero if stale or missing)
  --output=PATH  Target output file path (default: docs/commands.md)
  --help, -h     Show this help message`);
      return 0;
    } else {
      console.error(`Unknown argument: ${arg}`);
      return 1;
    }
  }

  if (checkMode) {
    const result = checkCommandDocs(targetPath);
    if (!result.ok) {
      console.error(`[check-command-docs] FAILED: ${result.reason}`);
      return 1;
    }
    console.log(`[check-command-docs] OK: ${targetPath} is up to date.`);
    return 0;
  }

  writeCommandDocs(targetPath);
  console.log(`[gen-command-docs] Wrote command documentation to ${targetPath}`);
  return 0;
}

// Auto-run if executed directly
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const exitCode = main();
  if (exitCode !== 0) {
    process.exit(exitCode);
  }
}
